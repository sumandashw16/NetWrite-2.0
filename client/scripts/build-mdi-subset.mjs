import * as mdi from '@mdi/js';
import { writeFileSync } from 'node:fs';

const CATS = [
  ['Essential UI', 'plus minus close check menu dots-horizontal dots-vertical magnify filter sort pencil delete content-copy content-save download'],
  ['Arrows & Flow', 'arrow-right arrow-left arrow-up arrow-down arrow-left-right arrow-up-down arrow-decision arrow-split-vertical arrow-expand arrow-collapse arrow-top-right arrow-bottom-left arrow-u-right-top arrow-u-left-bottom arrow-left-bold arrow-right-bold arrow-up-bold arrow-down-bold chevron-right swap-horizontal'],
  ['Shapes', 'circle square rectangle-outline triangle hexagon octagon rhombus star heart diamond-stone cube shape'],
  ['People', 'account account-circle account-group account-multiple account-tie account-supervisor account-plus account-cog human human-male human-female face-agent'],
  ['Devices', 'laptop desktop-tower monitor cellphone tablet keyboard mouse printer server server-network harddisk memory chip router-wireless usb'],
  ['Programming', 'code-tags code-braces code-json code-not-equal-variant console language-javascript language-python language-java language-cpp language-html5 language-css3 react nodejs github git git-branch source-branch api application-brackets bug'],
  ['Cloud', 'cloud cloud-outline cloud-upload cloud-download cloud-sync cloud-check cloud-lock cloud-cog docker kubernetes database database-cog web application lan lan-connect'],
  ['Networking', 'network access-point access-point-network router ethernet wifi wifi-strength-4 ip-network ip-network-outline websocket transit-connection transit-connection-variant'],
  ['Database', 'database-outline database-search database-plus database-minus database-check table table-large table-column folder folder-multiple'],
  ['Files', 'file file-document file-code file-pdf-box file-image file-video file-music file-excel file-word folder-open folder-zip clipboard-text'],
  ['Security', 'shield shield-check shield-lock shield-alert lock lock-open key key-variant fingerprint security two-factor-authentication eye'],
  ['Business', 'briefcase office-building bank cash currency-usd currency-inr credit-card wallet chart-box handshake store cart'],
  ['Data', 'chart-bar chart-line chart-pie chart-donut chart-scatter-plot chart-areaspline poll calculator table-pivot brain robot'],
  ['Communication', 'message message-text chat forum email bell video video-outline account-voice share-variant'],
  ['Media & Misc', 'image image-multiple palette brush vector-square puzzle lightbulb target']
];

const key = (n) => 'mdi' + n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const seen = new Set(), missing = [], paths = {}, cats = [];
for (const [title, list] of CATS) {
  const names = [];
  for (const n of list.split(' ')) {
    if (seen.has(n)) continue;
    seen.add(n);
    const p = mdi[key(n)];
    if (!p) { missing.push(n); continue; }
    paths[n] = p; names.push(n);
  }
  cats.push([title, names]);
}
writeFileSync('../src/components/canvas/mdiSubset.js',
  `// generated by scripts/build-mdi-subset.mjs\nexport const MDI_CATEGORIES = ${JSON.stringify(cats)};\nexport const MDI_PATHS = ${JSON.stringify(paths)};\n`);
console.log(`${Object.keys(paths).length} icons written. Missing: ${missing.join(', ') || 'none'}`);